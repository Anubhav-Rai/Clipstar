import AppKit
import UniformTypeIdentifiers

/// Hangs images copied to the clipboard, like a screenshot taken with Control
/// held or an image copied in Preview. Each one is saved as a PNG in
/// Clipstar's own folder, so on the line it behaves like any screenshot.
///
/// Off until the user turns it on. The pasteboard has no change notification,
/// so its change count is checked twice a second; what was copied is only read
/// once its types say it is a picture and nothing else.
@MainActor
final class ClipboardWatcher {
    private let onImage: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last image saved. Some apps put the same image on the clipboard
    /// again; it hangs once, unless it has been taken down since.
    private var last: (png: Data, url: URL)?

    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Copies that carry a picture but are not one. Text from a spreadsheet
    /// or a document also comes as an image of itself. A file copied in
    /// Finder brings its icon, and a photo copied from the line brings its
    /// file. Password managers and similar apps mark private or temporary
    /// copies, following nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .string, .fileURL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// What password managers and similar apps mark as private or temporary.
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Anything bigger is not a screenshot.
    nonisolated private static let maxBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000

    init(onImage: @escaping (URL) -> Void) {
        self.onImage = onImage
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        // Copied on the iPhone and handed over by Universal Clipboard. Only
        // with Dock iPhone copies on, whatever the Mac's own switches say.
        if let items = pb.pasteboardItems, items.contains(where: { $0.types.contains(Self.remoteType) }) {
            if Self.isRemoteEnabled { fetchRemote(count) }
            return
        }
        // Image files copied in Finder dock as they are, from where they
        // live; nothing is copied into Clipstar's folder. A file already docked,
        // like one copied from the dock itself, is not docked twice.
        if Self.isEnabled, let items = pb.pasteboardItems, !items.isEmpty,
           items.allSatisfy({ Self.privateTypes.isDisjoint(with: $0.types) }),
           let files = pb.readObjects(forClasses: [NSURL.self], options: [
               .urlReadingFileURLsOnly: true,
               .urlReadingContentsConformToTypes: [UTType.image.identifier],
           ]) as? [URL], files.count == items.count {
            files.forEach(onImage)
            return
        }
        // Copied text, unless private or temporary, or a file's name.
        if Self.isTextEnabled, let items = pb.pasteboardItems, !items.isEmpty,
           items.allSatisfy({ Self.privateTypes.isDisjoint(with: $0.types) && !$0.types.contains(.fileURL) }),
           pb.availableType(from: [.png, .tiff]) == nil,
           let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= 1_000_000 {
            saveText(text)
            return
        }
        guard Self.isEnabled, let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }),
              let type = pb.availableType(from: [.png, .tiff]),
              let data = pb.data(forType: type), data.count <= Self.maxBytes,
              pb.changeCount == count else { return }
        // Decoding a large image takes a moment, so it happens off the main thread.
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let png = ClipboardWatcher.png(from: data, type: type)
            DispatchQueue.main.async {
                // Copied over again in the meantime: that copy is the one that counts.
                guard let png, NSPasteboard.general.changeCount == count else { return }
                self?.save(png)
            }
        }
    }

    /// PNG bytes are kept as they are; TIFF becomes PNG. Either way the image
    /// must decode and have a sane size.
    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    /// macOS marks what came from another device with this.
    private static let remoteType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

    /// Dock iPhone copies, from the menu. Off until turned on.
    static var isRemoteEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: "iPhoneCopies") }
        set { UserDefaults.standard.set(newValue, forKey: "iPhoneCopies") }
    }

    /// The iPhone sends what was copied only once it is read, which takes a
    /// moment over the air, so it is read off the main thread and saved
    /// straight away: the Mac forgets it after a couple of minutes.
    private func fetchRemote(_ count: Int) {
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let pb = NSPasteboard.general
            var png: Data?
            var text: String?
            if let type = pb.availableType(from: [.png, .tiff]), let data = pb.data(forType: type),
               data.count <= ClipboardWatcher.maxBytes {
                png = ClipboardWatcher.png(from: data, type: type)
            } else if let string = pb.string(forType: .string),
                      !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, string.utf8.count <= 1_000_000 {
                text = string
            }
            DispatchQueue.main.async {
                // Copied over again in the meantime: that copy is the one that counts.
                guard let self, NSPasteboard.general.changeCount == count else { return }
                if let png { self.save(png, from: "iPhone") } else if let text { self.saveText(text, from: "iPhone") }
            }
        }
    }

    /// Copied text docks too, on by default; Dock copied text in the menu.
    static var isTextEnabled: Bool {
        get { UserDefaults.standard.object(forKey: "clipboardTextEnabled") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardTextEnabled") }
    }

    private var lastText: (text: String, url: URL)?

    /// Kept as a text file only you can read, in Clipstar's folder.
    private func saveText(_ text: String, from source: String = "Clipboard") {
        if let lastText, lastText.text == text, FileManager.default.fileExists(atPath: lastText.url.path) { return }
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("\(source) \(Self.stamp()).txt")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("\(source) \(Self.stamp()) \(n).txt")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            try Data(text.utf8).write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            lastText = (text, url)
            onImage(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save copied text: \(error.localizedDescription, privacy: .public)")
        }
    }

    private func save(_ png: Data, from source: String = "Clipboard") {
        if let last, last.png == png, FileManager.default.fileExists(atPath: last.url.path) { return }
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("\(source) \(Self.stamp()).png")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("\(source) \(Self.stamp()) \(n).png")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            try png.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            last = (png, url)
            onImage(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a copied image: \(error.localizedDescription, privacy: .public)")
        }
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
